-- Выполняется на координаторе и в монолитной БД PostgreSQL.
-- Таблицы на рабочих узлах вручную не создаются.

BEGIN;

CREATE TABLE IF NOT EXISTS order_statuses (
    status_id smallint PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS event_types (
    event_type_id smallint PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orders (
    user_id bigint NOT NULL,
    order_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    status_id smallint NOT NULL,
    total_amount numeric(14, 2) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT orders_pk PRIMARY KEY (user_id, order_id),
    CONSTRAINT orders_total_amount_positive CHECK (total_amount > 0)
);

CREATE TABLE IF NOT EXISTS events (
    user_id bigint NOT NULL,
    event_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    event_type_id smallint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT events_pk PRIMARY KEY (user_id, event_id),
    CONSTRAINT events_payload_is_object CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX IF NOT EXISTS orders_user_created_idx
    ON orders (user_id, created_at DESC, order_id DESC);

CREATE INDEX IF NOT EXISTS events_user_created_idx
    ON events (user_id, created_at DESC, event_id DESC);

COMMIT;
